const authored = (
    id: string,
    skill: SkillId,
    sentence: string,
    prompt: string,
    options: string[],
    answer: number,
    explanation: string,
    hints: string[],
    difficulty: 1 | 2 | 3 = 1,
): Exercise => ({
    id,
    skill,
    sentence,
    prompt,
    options,
    answer,
    explanation,
    hints,
    difficulty,
    feedback: options.map((_, i) =>
        i === answer
            ? explanation
            : (() => {
                  const feedback = misconceptions[id]?.[i];
                  if (!feedback) throw new Error(`Missing misconception feedback: ${id}/${i}`);
                  return feedback + " " + explanation;
              })(),
    ),
    source: { name: "Syntax authored curriculum", quote: sentence, location: `Item ${id}` },
    validation: "authored",
});

